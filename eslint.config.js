/**
 * @fileoverview Lint rules for the whole repository.
 *
 * Layers, from general to specific:
 * 1. Google's TypeScript style (gts), with formatting left to Prettier.
 * 2. typescript-eslint's strict, type-aware rules.
 * 3. React hooks rules for the browser app.
 * 4. Import boundaries between the three halves of the codebase:
 *    - src/client (browser) must never import src/worker (server-only code
 *      would leak into the public bundle);
 *    - src/worker must never import src/client;
 *    - src/shared must import neither, so it runs unchanged on both sides.
 */
import js from '@eslint/js';
import gts from 'gts';
import reactHooks from 'eslint-plugin-react-hooks';
import globals from 'globals';
import tseslint from 'typescript-eslint';

/** Builds a rule that forbids importing from the given source folders. */
function forbidImportsFrom(...folders) {
  return [
    'error',
    {
      patterns: folders.map(folder => ({
        group: [`@/${folder}/*`, `**/${folder}/*`],
        message: `This part of the codebase may not import from src/${folder}.`,
      })),
    },
  ];
}

export default tseslint.config(
  {
    ignores: [
      'dist/',
      'coverage/',
      'playwright-report/',
      'test-results/',
      '.wrangler/',
      'worker-configuration.d.ts',
      // Generated by shadcn/ui; kept as generated so updates apply cleanly.
      'src/client/components/ui/',
    ],
  },
  js.configs.recommended,
  ...gts,
  ...tseslint.configs.strictTypeChecked,
  {
    languageOptions: {
      parserOptions: {
        // gts points the parser at one tsconfig; this project has one per side,
        // so let typescript-eslint find the right one for each file instead.
        project: null,
        projectService: true,
        tsconfigRootDir: import.meta.dirname,
      },
    },
    rules: {
      // Template literals with numbers are common and clear in log messages.
      '@typescript-eslint/restrict-template-expressions': [
        'error',
        {allowNumber: true},
      ],
    },
  },
  {
    files: ['**/*.js'],
    ...tseslint.configs.disableTypeChecked,
    // This repo uses ES modules; gts assumes CommonJS config files.
    languageOptions: {
      ...tseslint.configs.disableTypeChecked.languageOptions,
      sourceType: 'module',
      globals: globals.node,
    },
  },
  {
    files: ['src/client/**/*.{ts,tsx}'],
    plugins: {'react-hooks': reactHooks},
    languageOptions: {globals: globals.browser},
    rules: {
      ...reactHooks.configs.recommended.rules,
      'no-restricted-imports': forbidImportsFrom('worker'),
    },
  },
  {
    files: ['src/worker/**/*.ts'],
    rules: {'no-restricted-imports': forbidImportsFrom('client')},
  },
  {
    files: ['src/shared/**/*.ts'],
    rules: {'no-restricted-imports': forbidImportsFrom('client', 'worker')},
  },
  {
    files: ['scripts/**/*.ts', 'tests/**/*.ts', '*.config.ts'],
    languageOptions: {globals: globals.node},
    rules: {
      // Node scripts may use process and console freely.
      'n/no-process-exit': 'off',
    },
  },
);
