-- Migration 0002: camera sources, the full cameras table, and search.
--
-- Replaces the provisional `cameras` table from 0001. That table only ever
-- held generated test data and no hosted database existed yet, so it is
-- dropped rather than migrated in place.
--
-- Column names are camelCase so rows map directly onto the API's JSON
-- shapes. Timestamps are ISO 8601 UTC text, for example 2026-11-17T12:00:00Z.

DROP TABLE IF EXISTS cameras;

-- Where cameras come from: one row per data provider, with the license and
-- attribution every camera from that provider must display.
CREATE TABLE sources (
  -- Short stable slug, for example "synthetic".
  id TEXT PRIMARY KEY NOT NULL,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
  homepageUrl TEXT CHECK (homepageUrl IS NULL OR homepageUrl LIKE 'https://%'),
  licenseName TEXT NOT NULL,
  attributionText TEXT NOT NULL,
  -- JSON array of the hostnames the server may fetch images or streams from
  -- for this source. Requests to any other host are refused.
  allowedHosts TEXT NOT NULL DEFAULT '[]' CHECK (json_valid(allowedHosts)),
  -- 1 when the source's terms allow commercial use (or a paid plan covers it).
  commercialUseAllowed INTEGER NOT NULL DEFAULT 0 CHECK (commercialUseAllowed IN (0, 1)),
  createdAt TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now')),
  updatedAt TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now'))
);

-- One row per public camera.
CREATE TABLE cameras (
  -- Public identifier, generated by the app.
  id TEXT PRIMARY KEY NOT NULL,
  sourceId TEXT NOT NULL REFERENCES sources (id) ON DELETE CASCADE,
  -- The provider's own identifier for the camera.
  externalId TEXT NOT NULL,
  title TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
  -- WGS 84 decimal degrees, the system GPS and Cesium use.
  lat REAL NOT NULL CHECK (lat BETWEEN -90 AND 90),
  lng REAL NOT NULL CHECK (lng BETWEEN -180 AND 180),
  -- Two-letter ISO 3166-1 country code, upper case.
  countryCode TEXT CHECK (countryCode IS NULL OR (length(countryCode) = 2 AND countryCode = upper(countryCode))),
  placeName TEXT CHECK (placeName IS NULL OR length(placeName) <= 200),
  -- IANA time zone name, for example "Asia/Tokyo".
  timeZone TEXT CHECK (timeZone IS NULL OR length(timeZone) <= 64),
  category TEXT NOT NULL
    CHECK (category IN ('city', 'nature', 'traffic', 'weather', 'landmark', 'beach', 'other')),
  -- How the camera is viewed; NULL means no feed is configured.
  streamType TEXT CHECK (streamType IS NULL OR streamType IN ('hls', 'youtube', 'embed', 'snapshot')),
  -- Where the feed lives (a URL or a provider ID). Used only on the server;
  -- the API never returns it.
  streamRef TEXT,
  -- online: shown on the globe. offline: not on the globe, but its page still
  -- works. hidden: never shown anywhere.
  status TEXT NOT NULL DEFAULT 'online' CHECK (status IN ('online', 'offline', 'hidden')),
  lastCheckedAt TEXT,
  consecutiveFailures INTEGER NOT NULL DEFAULT 0 CHECK (consecutiveFailures >= 0),
  createdAt TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now')),
  updatedAt TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now')),
  -- Re-importing the same provider camera updates it instead of duplicating it.
  UNIQUE (sourceId, externalId)
);

-- Finds visible cameras, and cameras inside a latitude/longitude box.
CREATE INDEX cameras_status_location ON cameras (status, lat, lng);

-- Finds the cameras whose health was checked longest ago.
CREATE INDEX cameras_status_last_checked ON cameras (status, lastCheckedAt);

-- Full-text search over camera names, places, and categories. The app keeps
-- it in step with `cameras` by writing both in one batch.
CREATE VIRTUAL TABLE cameras_fts USING fts5 (
  cameraId UNINDEXED,
  title,
  placeName,
  category,
  tokenize = 'unicode61 remove_diacritics 2'
);
